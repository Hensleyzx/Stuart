-- ============================================================
-- VENDAS
-- ============================================================

create table if not exists public.vendas (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  cliente_id uuid references public.clientes(id) on delete restrict,
  veiculo_id uuid references public.veiculos(id) on delete restrict,
  forma_pagamento text not null default 'PIX',
  subtotal_produtos numeric(12,2) not null default 0 check (subtotal_produtos >= 0),
  subtotal_servicos numeric(12,2) not null default 0 check (subtotal_servicos >= 0),
  subtotal_veiculo numeric(12,2) not null default 0 check (subtotal_veiculo >= 0),
  desconto numeric(12,2) not null default 0 check (desconto >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  observacoes text,
  criado_por uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists venda_veiculo_unica
on public.vendas (veiculo_id)
where veiculo_id is not null;

alter table public.vendas enable row level security;

create table if not exists public.itens_venda (
  id uuid primary key default gen_random_uuid(),
  venda_id uuid not null references public.vendas(id) on delete cascade,
  produto_id uuid references public.produtos(id) on delete restrict,
  descricao text not null,
  quantidade integer not null check (quantidade > 0),
  valor_unitario numeric(12,2) not null check (valor_unitario >= 0),
  valor_total numeric(12,2) not null check (valor_total >= 0),
  created_at timestamptz not null default now()
);

alter table public.itens_venda enable row level security;

create table if not exists public.servicos_venda (
  id uuid primary key default gen_random_uuid(),
  venda_id uuid not null references public.vendas(id) on delete cascade,
  descricao text not null,
  quantidade integer not null check (quantidade > 0),
  valor_unitario numeric(12,2) not null check (valor_unitario >= 0),
  valor_total numeric(12,2) not null check (valor_total >= 0),
  created_at timestamptz not null default now()
);

alter table public.servicos_venda enable row level security;

