-- ============================================================
-- VENDA ATÔMICA / SEGURA
-- O cliente envia IDs/quantidades. O banco usa os preços reais
-- dos produtos e do veículo, atualiza estoque e grava tudo na
-- mesma transação.
-- ============================================================

create or replace function public.registrar_venda(
  p_cliente jsonb,
  p_produtos jsonb default '[]'::jsonb,
  p_servicos jsonb default '[]'::jsonb,
  p_veiculo_id uuid default null,
  p_forma_pagamento text default 'PIX',
  p_desconto numeric default 0,
  p_observacoes text default null
)
returns table (
  venda_id uuid,
  numero bigint,
  total numeric
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_cliente_id uuid;
  v_venda_id uuid;
  v_numero bigint;

  v_sub_prod numeric(12,2) := 0;
  v_sub_serv numeric(12,2) := 0;
  v_sub_vehicle numeric(12,2) := 0;
  v_total numeric(12,2) := 0;

  v_item jsonb;
  v_prod_id uuid;
  v_qty integer;
  v_service_price numeric(12,2);
  v_line_total numeric(12,2);

  v_product record;
  v_vehicle record;
begin
  if not public.is_owner() then
    raise exception 'Somente o dono pode registrar vendas';
  end if;

  if coalesce(trim(p_cliente->>'nome'),'') = '' then
    raise exception 'Nome do cliente é obrigatório';
  end if;

  if jsonb_array_length(coalesce(p_produtos,'[]'::jsonb)) = 0
     and jsonb_array_length(coalesce(p_servicos,'[]'::jsonb)) = 0
     and p_veiculo_id is null then
    raise exception 'A venda precisa ter produto, serviço ou veículo';
  end if;

  if coalesce(p_desconto,0) < 0 then
    raise exception 'Desconto inválido';
  end if;

  insert into public.clientes (
    nome, cpf_cnpj, telefone, email, endereco
  ) values (
    trim(p_cliente->>'nome'),
    nullif(trim(p_cliente->>'cpf_cnpj'),''),
    nullif(trim(p_cliente->>'telefone'),''),
    nullif(trim(p_cliente->>'email'),''),
    nullif(trim(p_cliente->>'endereco'),'')
  )
  returning id into v_cliente_id;

  if p_veiculo_id is not null then
    select *
      into v_vehicle
      from public.veiculos
     where id = p_veiculo_id
     for update;

    if not found then
      raise exception 'Veículo não encontrado';
    end if;

    if v_vehicle.vendido then
      raise exception 'Veículo já foi vendido';
    end if;

    v_sub_vehicle := v_vehicle.preco;
  end if;

  insert into public.vendas (
    cliente_id,
    veiculo_id,
    forma_pagamento,
    subtotal_produtos,
    subtotal_servicos,
    subtotal_veiculo,
    desconto,
    total,
    observacoes,
    criado_por
  ) values (
    v_cliente_id,
    p_veiculo_id,
    coalesce(nullif(trim(p_forma_pagamento),''),'PIX'),
    0,0,v_sub_vehicle,
    coalesce(p_desconto,0),
    0,
    p_observacoes,
    auth.uid()
  )
  returning id, public.vendas.numero
  into v_venda_id, v_numero;

  for v_item in
    select value from jsonb_array_elements(coalesce(p_produtos,'[]'::jsonb))
  loop
    v_prod_id := (v_item->>'produto_id')::uuid;
    v_qty := greatest(coalesce((v_item->>'quantidade')::integer,1),1);

    select id,nome,preco,quantidade,ativo
      into v_product
      from public.produtos
     where id = v_prod_id
     for update;

    if not found then
      raise exception 'Produto não encontrado';
    end if;

    if not v_product.ativo then
      raise exception 'Produto % está inativo', v_product.nome;
    end if;

    if v_product.quantidade < v_qty then
      raise exception 'Estoque insuficiente para %', v_product.nome;
    end if;

    v_line_total := v_product.preco * v_qty;
    v_sub_prod := v_sub_prod + v_line_total;

    insert into public.itens_venda (
      venda_id, produto_id, descricao, quantidade,
      valor_unitario, valor_total
    ) values (
      v_venda_id, v_product.id, v_product.nome, v_qty,
      v_product.preco, v_line_total
    );

    update public.produtos
       set quantidade = quantidade - v_qty
     where id = v_product.id;
  end loop;

  for v_item in
    select value from jsonb_array_elements(coalesce(p_servicos,'[]'::jsonb))
  loop
    if coalesce(trim(v_item->>'descricao'),'') = '' then
      raise exception 'Descrição da mão de obra é obrigatória';
    end if;

    v_qty := greatest(coalesce((v_item->>'quantidade')::integer,1),1);
    v_service_price := coalesce((v_item->>'valor_unitario')::numeric,0);

    if v_service_price < 0 then
      raise exception 'Valor de mão de obra inválido';
    end if;

    v_line_total := v_service_price * v_qty;
    v_sub_serv := v_sub_serv + v_line_total;

    insert into public.servicos_venda (
      venda_id, descricao, quantidade, valor_unitario, valor_total
    ) values (
      v_venda_id,
      trim(v_item->>'descricao'),
      v_qty,
      v_service_price,
      v_line_total
    );
  end loop;

  if p_veiculo_id is not null then
    update public.veiculos
       set vendido = true
     where id = p_veiculo_id;
  end if;

  v_total := greatest(
    0,
    v_sub_prod + v_sub_serv + v_sub_vehicle - coalesce(p_desconto,0)
  );

  update public.vendas
     set subtotal_produtos = v_sub_prod,
         subtotal_servicos = v_sub_serv,
         subtotal_veiculo = v_sub_vehicle,
         total = v_total
   where id = v_venda_id;

  return query
    select v_venda_id, v_numero, v_total;
end;
$$;

revoke all on function public.registrar_venda(jsonb,jsonb,jsonb,uuid,text,numeric,text) from public;
grant execute on function public.registrar_venda(jsonb,jsonb,jsonb,uuid,text,numeric,text) to authenticated;

