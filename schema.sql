create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('owner')),
  created_at timestamptz not null default now()
);

alter table public.user_roles enable row level security;

create or replace function public.is_owner()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.user_roles
    where user_id = (select auth.uid())
      and role = 'owner'
  );
$$;

revoke all on function public.is_owner() from public;
grant execute on function public.is_owner() to authenticated;

-- ============================================================
-- PRODUTOS
-- ============================================================

create table if not exists public.produtos (
  id uuid primary key default gen_random_uuid(),
  nome text not null,
  categoria text not null,
  marca text,
  sku text,
  preco numeric(12,2) not null default 0 check (preco >= 0),
  quantidade integer not null default 0 check (quantidade >= 0),
  estoque_minimo integer not null default 0 check (estoque_minimo >= 0),
  ativo boolean not null default true,
  criado_por uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists produtos_sku_unique
on public.produtos (sku)
where sku is not null and sku <> '';

alter table public.produtos enable row level security;

-- ============================================================
-- VEÍCULOS
-- ============================================================

create table if not exists public.veiculos (
  id uuid primary key default gen_random_uuid(),
  marca text not null,
  modelo text not null,
  ano integer not null check (ano between 1950 and 2100),
  cor text,
  quilometragem integer not null default 0 check (quilometragem >= 0),
  preco numeric(12,2) not null default 0 check (preco >= 0),
  placa text,
  renavam text,
  observacoes text,
  vendido boolean not null default false,
  publicado boolean not null default true,
  criado_por uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists veiculos_placa_unique
on public.veiculos (upper(placa))
where placa is not null and placa <> '';

alter table public.veiculos enable row level security;

