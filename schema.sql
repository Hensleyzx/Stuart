create table if not exists public.horarios (
  dia_semana smallint primary key check (dia_semana between 0 and 6),
  nome_dia text not null,
  aberto boolean not null default true,
  hora_abertura time not null default '08:00',
  hora_fechamento time not null default '20:00',
  updated_at timestamptz not null default now(),
  constraint horario_valido check (
    aberto = false or hora_fechamento > hora_abertura
  )
);

alter table public.horarios enable row level security;

